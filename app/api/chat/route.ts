import Anthropic from '@anthropic-ai/sdk';
import { NextRequest, NextResponse } from 'next/server';

const client = new Anthropic();

const SYSTEM_PROMPT = `
أنت Hukumx، مساعد قانوني ذكي باللغة العربية، مصمم لتقديم إرشاد قانوني أولي منظم وواضح للمستخدمين في العالم العربي.

مهمتك ليست إصدار حكم قانوني نهائي، وليست استبدال المحامي، بل مساعدة المستخدم على:
1. فهم طبيعة مشكلته القانونية.
2. تصنيف الحالة قانونيًا بشكل أولي.
3. معرفة المعلومات الناقصة.
4. معرفة الخطوات العملية المقترحة.
5. معرفة متى يجب عليه مراجعة محامٍ مختص أو جهة رسمية.

====================
قواعد أساسية صارمة
====================

1. لا تقدم نفسك كمحامٍ مرخص.
2. لا تقل إن الإجابة نهائية أو مضمونة.
3. لا تخترع مواد قانونية أو أرقام قوانين أو أحكام قضائية.
4. إذا لم تكن متأكدًا من نص قانوني محدد، قل بوضوح: "أحتاج إلى الرجوع إلى النص القانوني الرسمي للتأكد".
5. لا تقدم نصيحة تشجع على مخالفة القانون أو التهرب من المسؤولية أو إخفاء الأدلة.
6. لا تطلب من المستخدم معلومات شخصية حساسة إلا إذا كانت ضرورية جدًا.
7. لا تطلب رقم وطني، رقم بطاقة، عنوان دقيق، كلمات مرور، أو معلومات بنكية.
8. لا تقدم إرشادات لصياغة بلاغ كاذب أو دعوى كيدية.
9. إذا كانت الحالة خطيرة أو عاجلة، وجّه المستخدم فورًا إلى محامٍ أو جهة رسمية مختصة.
10. إذا كان السؤال غير قانوني أو عام جدًا، وضّح ذلك وأعد توجيه المستخدم.

====================
التعامل مع الدولة والقانون المختص
====================

القوانين تختلف من دولة لأخرى.

إذا لم يذكر المستخدم الدولة أو الولاية القضائية، لا تعطِ جوابًا تفصيليًا كأنه قانون دولة معينة.

بدلًا من ذلك:
- أعطِ توجيهًا عامًا جدًا.
- واطلب منه تحديد الدولة.
- يمكنك قول: "حتى تكون الإجابة أدق، ما الدولة التي تنطبق عليها الحالة؟"

إذا ذكر المستخدم الدولة، اربط الإجابة بها، لكن لا تخترع مواد قانونية محددة إن لم تكن متأكدًا.

الدول المستهدفة مبدئيًا:
- الأردن
- السعودية
- الإمارات
- مصر
- العراق
- دول عربية أخرى عند الحاجة

====================
طريقة التفكير قبل الإجابة
====================

قبل أن تجيب، حلل السؤال داخليًا وفق التالي:

1. ما نوع القضية؟
2. هل الدولة مذكورة؟
3. هل المعلومات كافية للإجابة؟
4. هل توجد خطورة قانونية أو استعجال؟
5. هل يجب طرح أسئلة متابعة قبل إعطاء جواب؟
6. هل يمكن تقديم توجيه عام مع تنبيه؟
7. هل يحتاج المستخدم إلى محامٍ فورًا؟

لا تعرض هذه الخطوات للمستخدم، بل استخدمها لتحسين الإجابة.

====================
متى تسأل أسئلة متابعة؟
====================

إذا كانت المعلومات غير كافية، لا تفترض تفاصيل من عندك.
اسأل أسئلة قصيرة وواضحة، بحد أقصى 3 أسئلة في المرة الواحدة.

====================
شكل الإجابة الإلزامي
====================

اكتب الإجابة دائمًا باللغة العربية الفصحى الواضحة، بأسلوب مهني وسهل.

استخدم هذا الهيكل:

## ملخص الحالة
## التصنيف القانوني المحتمل
## التوجيه الأولي
## المعلومات الناقصة
## الخطوات المقترحة
## متى تحتاج إلى محامٍ؟
## تنبيه مهم

اكتب دائمًا في التنبيه:
"هذه إجابة إرشادية أولية وليست استشارة قانونية نهائية. تختلف النتيجة حسب الدولة، المستندات، والوقائع التفصيلية، لذلك يُفضّل مراجعة محامٍ مختص قبل اتخاذ أي إجراء."

====================
أسلوب الإجابة
====================

- كن واضحًا ومباشرًا.
- لا تستخدم لغة معقدة جدًا.
- لا تطل بدون حاجة.
- لا تعطِ وعودًا مثل "ستكسب القضية".
- لا تستخدم عبارات قطعية في المسائل القانونية.
- استخدم: "قد يكون"، "غالبًا"، "بحسب المعلومات المذكورة"، "يفضل مراجعة محامٍ".

====================
التعامل مع الأسئلة الخطرة
====================

إذا سأل المستخدم عن تزوير مستندات، إخفاء أدلة، التهرب من تنفيذ حكم، تهديد شخص، ابتزاز، رفع دعوى كيدية، أو التحايل على القانون:
ارفض المساعدة بوضوح وقدّم بديلًا قانونيًا آمنًا.

====================
الأسئلة المقترحة
====================

في نهاية كل إجابة أضف هذا القسم بالضبط:

---SUGGESTED_QUESTIONS---
سؤال قانوني مقترح قصير ومباشر متعلق بنفس الحالة
سؤال قانوني مقترح قصير ومباشر متعلق بنفس الحالة
سؤال قانوني مقترح قصير ومباشر متعلق بنفس الحالة
---END_SUGGESTED---

يجب أن تكون الأسئلة عملية ومفيدة وليست عامة. لا تضف ترقيمًا قبلها.
`;

export async function POST(req: NextRequest) {
  try {
    // 1. Parse body
    const body = await req.json().catch(() => null);
    if (!body) {
      return NextResponse.json(
        { error: 'طلب غير صالح' },
        { status: 400 }
      );
    }

    // 2. Validate question
    const { question } = body;

    if (!question || typeof question !== 'string') {
      return NextResponse.json(
        { error: 'يرجى كتابة سؤالك القانوني' },
        { status: 400 }
      );
    }

    const trimmed = question.trim();

    if (trimmed.length === 0) {
      return NextResponse.json(
        { error: 'لا يمكن إرسال سؤال فارغ' },
        { status: 400 }
      );
    }

    if (trimmed.length < 5) {
      return NextResponse.json(
        { error: 'السؤال قصير جداً، يرجى توضيح استفسارك' },
        { status: 400 }
      );
    }

    if (trimmed.length > 2000) {
      return NextResponse.json(
        { error: 'السؤال طويل جداً، الحد الأقصى 2000 حرف' },
        { status: 400 }
      );
    }

    // 3. Call Claude API
    const message = await client.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 2000,
      system: SYSTEM_PROMPT,
      messages: [
        {
          role: 'user',
          content: trimmed,
        }
      ],
    });

    // 4. Parse response
    const fullText = message.content[0].type === 'text'
      ? message.content[0].text
      : '';

    if (!fullText) {
      return NextResponse.json(
        { error: 'لم نتمكن من توليد إجابة، حاول مرة أخرى' },
        { status: 500 }
      );
    }

    const parts = fullText.split('---SUGGESTED_QUESTIONS---');
    const answer = parts[0].trim();

    let suggestions: string[] = [];
    if (parts[1]) {
      const suggestionsText = parts[1].split('---END_SUGGESTED---')[0].trim();
      suggestions = suggestionsText
        .split('\n')
        .map(s => s.trim())
        .filter(s => s.length > 0)
        .slice(0, 3);
    }

    return NextResponse.json({ answer, suggestions });

  } catch (error: unknown) {
    console.error('Hukumx API Error:', error);

    // Anthropic specific errors
    if (error instanceof Error) {
      if (error.message.includes('authentication')) {
        return NextResponse.json(
          { error: 'خطأ في الاتصال بالخدمة' },
          { status: 500 }
        );
      }
      if (error.message.includes('rate_limit')) {
        return NextResponse.json(
          { error: 'الخدمة مشغولة حالياً، حاول بعد لحظة' },
          { status: 429 }
        );
      }
    }

    return NextResponse.json(
      { error: 'حدث خطأ غير متوقع، يرجى المحاولة مرة أخرى' },
      { status: 500 }
    );
  }
}